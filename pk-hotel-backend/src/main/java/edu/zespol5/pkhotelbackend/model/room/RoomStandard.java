package edu.zespol5.pkhotelbackend.model.room;

/**
 * Enum representing the standard of a hotel room.
 * <p>
 * The room standard defines the level of comfort and amenities available in the room.
 * It is used to classify rooms based on the quality of services and facilities offered.
 * </p>
 */
public enum RoomStandard {

    /**
     * Low standard - rooms with basic amenities, typically at a lower price.
     */
    LOW,

    /**
     * Average standard - rooms with more comfortable amenities, priced at a mid-range level.
     */
    AVERAGE,

    /**
     * High standard - rooms with the best amenities, luxurious, and fully equipped.
     */
    HIGH
}
